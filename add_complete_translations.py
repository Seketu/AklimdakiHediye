# Gerçek çeviriler yapılması gerekiyor. Burada basit bir sözlük oluşturacağım.
# Tüm 7 dil için komplett çeviriler yazacağım.

base_path = 'app/src/main/res'
total_added = 0

for lang_folder, lang_strings in complete_translations.items():
    file_path = os.path.join(base_path, lang_folder, 'strings.xml')

    if not os.path.exists(file_path):
        print(f'✗ {lang_folder}: Dosya bulunamadı')
        continue

    try:
        tree = ET.parse(file_path)
        root = tree.getroot()

        existing_names = {elem.get('name') for elem in root.findall('string')}

        added = 0
        for name, value in lang_strings.items():
            if name not in existing_names:
                new_elem = ET.Element('string')
                new_elem.set('name', name)
                new_elem.text = value
                root.append(new_elem)
                added += 1
                total_added += 1

        tree.write(file_path, encoding='utf-8', xml_declaration=True)
        print(f'✓ {lang_folder}: {added} yeni string eklendi (Toplam: {len(existing_names) + added})')

    except Exception as e:
        print(f'✗ {lang_folder}: Hata - {str(e)}')

print(f'\n✓ Toplam {total_added} string eklendi!')

